KANJI = {"一": "1", "二": "2", "三": "3", "四": "4", "五": "5",
         "六": "6", "七": "7", "八": "8", "九": "9", "十": "10", "元": "1"}

# 「創始」を示す文脈語。この語の周辺 ±60 文字に出る年号を採用する。
ORIGIN_CUES = [
    "創始", "始まり", "始まっ", "始まる", "起源", "creation", "創建", "創祀", "創設",
    "由来", "起こり", "はじまり", "以来", "から続く", "から行われ", "から続いて",
    "に始", "が始", "を起源", "発祥", "初めて行", "初めとする",
]


def _z2h(s: str) -> str:
    return unicodedata.normalize("NFKC", s or "")


def _kanji_year(s: str) -> int | None:
    s = s.strip()
    if s.isdigit():
        return int(s)
    if s == "元":
        return 1
    if len(s) == 1 and s in KANJI:
        return int(KANJI[s])
    m = re.fullmatch(r"十([一二三四五六七八九])?", s)
    if m:
        return 10 + (int(KANJI[m.group(1)]) if m.group(1) else 0)
    m = re.fullmatch(r"([一二三四五六七八九])十([一二三四五六七八九])?", s)
    if m:
        return int(KANJI[m.group(1)]) * 10 + (int(KANJI[m.group(2)]) if m.group(2) else 0)
    return None


def find_years(text: str) -> list[tuple[int, str, int]]:
    """本文から (西暦, 種別, 出現位置) をすべて拾う。種別: exact / era / jidai"""
    if not text:
        return []
    t = _z2h(text)
    out: list[tuple[int, str, int]] = []

    # 西暦4桁（1000-2100）
    for m in re.finditer(r"(?<!\d)(1[0-9]{3}|20[0-9]{2})年", t):
        y = int(m.group(1))
        if 600 <= y <= 2100:
            out.append((y, "exact", m.start()))

    # 元号+年
    era_pat = "|".join(sorted(GENGO, key=len, reverse=True))
    for m in re.finditer(rf"({era_pat})([0-9]{{1,2}}|元|[一二三四五六七八九十]{{1,3}})年", t):
        n = _kanji_year(m.group(2))
        if n:
            out.append((GENGO[m.group(1)] + n - 1, "era", m.start()))

    # 時代名
    for name, y in JIDAI.items():
        for m in re.finditer(re.escape(name), t):
            out.append((y, "jidai", m.start()))

    return out


def estimate_founded(text: str, has_designation: bool = False) -> tuple[int | None, str]:
    """
    (推定創始年, 確度) を返す。確度は
      "exact"     … 創始文脈のすぐそばに西暦/元号があった
      "estimated" … 本文中の最古の年、または時代名からの推定
      "proxy"     … 年の記述はないが文化財指定などから 50 年以上と判断
      "unknown"   … 判断材料なし
    """
    years = find_years(text)
    t = _z2h(text or "")

    # 1) 創始文脈の近傍
    cue_pos = [m.start() for cue in ORIGIN_CUES for m in re.finditer(re.escape(cue), t)]
    if cue_pos and years:
        near = [(y, kind, pos) for (y, kind, pos) in years
                if any(abs(pos - c) <= 60 for c in cue_pos)]
        if near:
            exact = [y for y, k, _ in near if k in ("exact", "era")]
            if exact:
                return min(exact), "exact"
            return min(y for y, _, _ in near), "estimated"

    # 2) 本文中の最古の年（1868年以前なら十分古い）
    hard = [y for y, k, _ in years if k in ("exact", "era")]
    if hard:
        oldest = min(hard)
        if oldest <= 1975:
            return oldest, "estimated"

    # 3) 時代名のみ
    jid = [y for y, k, _ in years if k == "jidai"]
    if jid:
        return min(jid), "estimated"

    # 4) 文化財指定などの代理指標
    if has_designation:
        return None, "proxy"

    return None, "unknown"
