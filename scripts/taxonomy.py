def tag_text(text: str) -> list:
    """記事本文からタグIDのリストを返す。"""
    if not text:
        return []
    found = []
    for tid, (_grp, _label, kws) in TAGS.items():
        if not kws:
            continue
        for kw in kws:
            if kw in text:
                found.append(tid)
                break
    return found


def group_label(gid: str) -> str:
    for g, label in GROUPS:
        if g == gid:
            return label
    return gid


def tags_json() -> dict:
    """フロントエンドに渡すタグ定義（キーワードは除く）。"""
    return {
        "groups": [{"id": g, "label": l} for g, l in GROUPS],
        "tags": [
            {"id": tid, "group": grp, "label": label}
            for tid, (grp, label, _kw) in TAGS.items()
        ],
        "ageBuckets": [{"years": y, "label": l} for y, l in AGE_BUCKETS],
    }
