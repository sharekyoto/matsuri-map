def build():
    out = []
    for (name, pref, city, lat, lng, when, founded, tags, note) in F:
        occ, rules = D.occurrences(when, YEARS)
        months = D.month_hint(rules)
        tags = sorted(set(tags) | set(D.season_tags(months)))
        age = (THIS_YEAR - founded) if founded else None
        conf = "exact" if founded else ("proxy" if set(tags) & TX.AGE_PROXY_TAGS else "assumed")
        out.append({
            "id": "seed_" + name.replace(" ", "_"),
            "name": name, "pref": pref, "city": city,
            "lat": lat, "lng": lng, "qid": None,
            "url": "https://ja.wikipedia.org/wiki/" + name.split("（")[0],
            "summary": note, "when": when,
            "months": months, "occ": occ[:8], "tags": tags,
            "founded": founded, "age": age, "ageConf": conf,
            "over50": True,
            "irregular": any(r["kind"] == "irregular" for r in rules) or "一度" in when or "年に" in when,
            "src": "seed",
        })
    out.sort(key=lambda r: (r["months"][0] if r["months"] else 13, r["name"]))
    payload = {
        "generated": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "years": YEARS, "count": len(out),
        "note": "手作業でキュレーションした初期データ。scripts/build.py を実行すると数千件の完全版に置き換わります。",
        "taxonomy": TX.tags_json(),
        "festivals": out,
    }
    os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
    path = os.path.join(ROOT, "data", "seed.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, separators=(",", ":"))
    print(f"{path}  {len(out)} 件  {os.path.getsize(path)/1024:.0f} KB")

    # 開催日が展開できなかったものを警告
    bad = [r["name"] for r in out if not r["occ"]]
    if bad:
        print("開催日を展開できなかった項目:", bad)
    nom = [r["name"] for r in out if not r["months"]]
    if nom:
        print("開催月が取れなかった項目:", nom)


if __name__ == "__main__":
    build()
